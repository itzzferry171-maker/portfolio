function translatePage(lang) {
    const selectedLang = Object.prototype.hasOwnProperty.call(translations, lang) ? lang : 'en';
    const dictionary = translations[selectedLang];
    document.documentElement.lang = selectedLang;

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
            el.textContent = dictionary[key];
        }
    });

    document.querySelectorAll('[data-i18n-html]').forEach(el => {
        const key = el.getAttribute('data-i18n-html');
        if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
            el.innerHTML = dictionary[key];
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
            el.placeholder = dictionary[key];
        }
    });

    document.querySelectorAll('[data-i18n-full-desc]').forEach(el => {
        const key = el.getAttribute('data-i18n-full-desc');
        if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
            el.dataset.fullDesc = dictionary[key];
        }
    });

    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === selectedLang);
    });

    window.dispatchEvent(new CustomEvent('languagechange', { detail: { lang: selectedLang } }));
}

window.addEventListener('DOMContentLoaded', () => {
    const fadeElements = document.querySelectorAll('.fade-init');

    setTimeout(() => {
        fadeElements.forEach(el => {
            el.classList.add('visible');
        });
    }, 150);

    const savedLang = localStorage.getItem('preferredLanguage');
    const initialLang = savedLang && Object.prototype.hasOwnProperty.call(translations, savedLang) ? savedLang : 'en';
    translatePage(initialLang);

    document.querySelectorAll('.lang-btn').forEach(button => {
        button.addEventListener('click', () => {
            const selectedLang = button.dataset.lang;
            if (!Object.prototype.hasOwnProperty.call(translations, selectedLang)) return;
            translatePage(selectedLang);
            localStorage.setItem('preferredLanguage', selectedLang);
        });
    });

    const certificateViewer = document.createElement('div');
    certificateViewer.className = 'certificate-viewer';
    certificateViewer.hidden = true;
    certificateViewer.setAttribute('role', 'dialog');
    certificateViewer.setAttribute('aria-modal', 'true');
    certificateViewer.setAttribute('aria-labelledby', 'certificateViewerTitle');

    const viewerContent = document.createElement('div');
    viewerContent.className = 'certificate-viewer-content';

    const closeViewerButton = document.createElement('button');
    closeViewerButton.className = 'certificate-viewer-close';
    closeViewerButton.type = 'button';
    closeViewerButton.setAttribute('aria-label', 'Close certificate viewer');
    closeViewerButton.textContent = '×';

    const viewerTitle = document.createElement('h2');
    viewerTitle.className = 'certificate-viewer-title';
    viewerTitle.id = 'certificateViewerTitle';

    const viewerImages = document.createElement('div');
    viewerImages.className = 'certificate-viewer-images';

    viewerContent.append(closeViewerButton, viewerTitle, viewerImages);
    certificateViewer.appendChild(viewerContent);
    document.body.appendChild(certificateViewer);

    let activeCertificateTrigger = null;
    let previousBodyOverflow = '';

    const closeCertificateViewer = () => {
        if (certificateViewer.hidden) return;
        certificateViewer.hidden = true;
        viewerImages.replaceChildren();
        document.body.style.overflow = previousBodyOverflow;
        activeCertificateTrigger?.focus();
        activeCertificateTrigger = null;
    };

    document.querySelectorAll('.certificate-trigger[data-certificate-images]').forEach(trigger => {
        trigger.addEventListener('click', () => {
            activeCertificateTrigger = trigger;
            previousBodyOverflow = document.body.style.overflow;
            viewerTitle.textContent = trigger.querySelector('span').textContent.trim();
            viewerImages.replaceChildren();

            const imagePaths = trigger.dataset.certificateImages.split('|').filter(Boolean);
            imagePaths.forEach((path, index) => {
                const image = document.createElement('img');
                image.src = encodeURI(path);
                image.alt = `${viewerTitle.textContent} document ${index + 1}`;
                image.addEventListener('error', () => {
                    console.error(`Unable to load certificate image: ${image.src}`);
                    image.remove();
                });
                viewerImages.appendChild(image);
            });

            certificateViewer.hidden = false;
            document.body.style.overflow = 'hidden';
            closeViewerButton.focus();
        });
    });

    closeViewerButton.addEventListener('click', closeCertificateViewer);
    certificateViewer.addEventListener('click', event => {
        if (event.target === certificateViewer) closeCertificateViewer();
    });
    window.addEventListener('keydown', event => {
        if (event.key === 'Escape') closeCertificateViewer();
    });
});
